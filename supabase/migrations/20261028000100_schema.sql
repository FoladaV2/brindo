-- Brindo v1 schema: invitations, guests, rsvps, orders, webhook_events, rate_limits.
-- Access rules live in the next migration (rls). Storage lives in the one after.

-- Shared trigger: keep updated_at current on every update.
create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Invitations ---------------------------------------------------------------

create table public.invitations (
  id          uuid primary key default gen_random_uuid(),
  owner_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  slug        text not null unique
              constraint invitations_slug_format check (slug ~ '^[a-z0-9][a-z0-9-]{1,58}[a-z0-9]$'),
  template_id text not null
              constraint invitations_template_id_known check (template_id in ('lumiere', 'noir')),
  content     jsonb not null default '{}'::jsonb
              constraint invitations_content_object check (jsonb_typeof(content) = 'object')
              constraint invitations_content_size check (octet_length(content::text) <= 65536),
  status      text not null default 'draft'
              constraint invitations_status_known check (status in ('draft', 'paid', 'published')),
  paid_at     timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- A draft has never been paid for; paid and published invitations always have a payment time.
  constraint invitations_paid_at_matches_status
    check ((status = 'draft') = (paid_at is null))
);

create index invitations_owner_id_idx on public.invitations (owner_id);

create trigger invitations_set_updated_at
  before update on public.invitations
  for each row execute function public.set_updated_at();

-- Guests --------------------------------------------------------------------
-- Only a name and a party-size limit. No phone numbers, no emails.

create table public.guests (
  id             uuid primary key default gen_random_uuid(),
  invitation_id  uuid not null references public.invitations (id) on delete cascade,
  name           text not null
                 constraint guests_name_length check (char_length(btrim(name)) between 1 and 120),
  -- 24 random bytes from pgcrypto's CSPRNG, base64url without padding (32 chars).
  -- Generated by the database so no client can choose or weaken a token.
  token          text not null unique
                 default rtrim(translate(encode(extensions.gen_random_bytes(24), 'base64'), '+/', '-_'), '=')
                 constraint guests_token_format check (token ~ '^[A-Za-z0-9_-]{32,}$'),
  max_party_size smallint not null default 1
                 constraint guests_max_party_size_range check (max_party_size between 1 and 20),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index guests_invitation_id_idx on public.guests (invitation_id);

create trigger guests_set_updated_at
  before update on public.guests
  for each row execute function public.set_updated_at();

-- RSVPs ---------------------------------------------------------------------
-- One row per guest. Cascades from invitations through guests.

create table public.rsvps (
  guest_id   uuid primary key references public.guests (id) on delete cascade,
  attending  boolean not null,
  party_size smallint not null
             constraint rsvps_party_size_range check (party_size between 0 and 20),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Declining means nobody comes; accepting means at least the guest comes.
  constraint rsvps_party_size_matches_attending
    check ((attending and party_size >= 1) or (not attending and party_size = 0))
);

create function public.check_rsvp_party_size()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  max_size smallint;
begin
  select g.max_party_size into max_size from public.guests g where g.id = new.guest_id;
  if new.party_size > max_size then
    raise exception 'party_size % exceeds max_party_size %', new.party_size, max_size
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger rsvps_check_party_size
  before insert or update on public.rsvps
  for each row execute function public.check_rsvp_party_size();

create trigger rsvps_set_updated_at
  before update on public.rsvps
  for each row execute function public.set_updated_at();

-- Orders --------------------------------------------------------------------
-- Financial records outlive the invitation: deleting an invitation keeps its order.

create table public.orders (
  id                  uuid primary key default gen_random_uuid(),
  invitation_id       uuid references public.invitations (id) on delete set null,
  provider            text not null default 'dodo'
                      constraint orders_provider_known check (provider in ('dodo')),
  provider_payment_id text unique,
  -- Minor units (tetri for GEL). Always set from server config, never from the client.
  amount              integer not null
                      constraint orders_amount_positive check (amount > 0),
  currency            text not null default 'GEL'
                      constraint orders_currency_format check (currency ~ '^[A-Z]{3}$'),
  status              text not null default 'pending'
                      constraint orders_status_known check (status in ('pending', 'paid', 'failed', 'refunded')),
  -- Referral code captured from ?ref=CODE. Stored only; payouts are manual.
  ref_code            text
                      constraint orders_ref_code_format check (ref_code ~ '^[A-Za-z0-9_-]{1,32}$'),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint orders_paid_has_payment_id
    check (status <> 'paid' or provider_payment_id is not null)
);

create index orders_invitation_id_idx on public.orders (invitation_id);

create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

-- Webhook events (idempotency) -----------------------------------------------

create table public.webhook_events (
  event_id    text primary key
              constraint webhook_events_event_id_length check (char_length(event_id) between 1 and 255),
  received_at timestamptz not null default now()
);

-- Rate limits (fixed windows, written by server code) --------------------------

create table public.rate_limits (
  key          text not null
               constraint rate_limits_key_length check (char_length(key) between 1 and 200),
  window_start timestamptz not null,
  count        integer not null default 0
               constraint rate_limits_count_nonnegative check (count >= 0),
  primary key (key, window_start)
);

-- Trigger functions are not meant to be called directly.
revoke execute on function public.set_updated_at() from public, anon, authenticated;
revoke execute on function public.check_rsvp_party_size() from public, anon, authenticated;
