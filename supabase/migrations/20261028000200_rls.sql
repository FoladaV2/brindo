-- Row-level security and table privileges.
--
-- Two layers, both required:
--   1. Privileges decide which roles may touch which tables and columns at all.
--      anon gets nothing. authenticated gets only the couple-facing tables, and only the columns a
--      couple may set (so nobody can mark their own invitation paid or published, or move rows
--      to another owner).
--   2. RLS policies decide which rows: only rows of invitations the couple owns.
-- rsvps, orders, webhook_events and rate_limits are written only by server code with the
-- service-role key, which bypasses RLS.

alter table public.invitations    enable row level security;
alter table public.guests         enable row level security;
alter table public.rsvps          enable row level security;
alter table public.orders         enable row level security;
alter table public.webhook_events enable row level security;
alter table public.rate_limits    enable row level security;

-- Supabase grants everything on new public tables to anon and authenticated by default.
revoke all on table
  public.invitations, public.guests, public.rsvps,
  public.orders, public.webhook_events, public.rate_limits
from anon, authenticated;

-- Invitations ---------------------------------------------------------------

grant select, delete on public.invitations to authenticated;
-- owner_id defaults to auth.uid(); status and paid_at change only through the payment webhook.
grant insert (slug, template_id, content) on public.invitations to authenticated;
grant update (slug, template_id, content) on public.invitations to authenticated;

create policy "Couples read their own invitations"
  on public.invitations for select to authenticated
  using (owner_id = (select auth.uid()));

create policy "Couples create invitations for themselves"
  on public.invitations for insert to authenticated
  with check (owner_id = (select auth.uid()));

create policy "Couples update their own invitations"
  on public.invitations for update to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy "Couples delete their own invitations"
  on public.invitations for delete to authenticated
  using (owner_id = (select auth.uid()));

-- Guests --------------------------------------------------------------------

grant select, delete on public.guests to authenticated;
-- token is generated by the database; a guest cannot be moved to another invitation.
grant insert (invitation_id, name, max_party_size) on public.guests to authenticated;
grant update (name, max_party_size) on public.guests to authenticated;

create policy "Couples read guests of their invitations"
  on public.guests for select to authenticated
  using (exists (
    select 1 from public.invitations i
    where i.id = guests.invitation_id and i.owner_id = (select auth.uid())
  ));

create policy "Couples add guests to their invitations"
  on public.guests for insert to authenticated
  with check (exists (
    select 1 from public.invitations i
    where i.id = guests.invitation_id and i.owner_id = (select auth.uid())
  ));

create policy "Couples update guests of their invitations"
  on public.guests for update to authenticated
  using (exists (
    select 1 from public.invitations i
    where i.id = guests.invitation_id and i.owner_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.invitations i
    where i.id = guests.invitation_id and i.owner_id = (select auth.uid())
  ));

create policy "Couples delete guests of their invitations"
  on public.guests for delete to authenticated
  using (exists (
    select 1 from public.invitations i
    where i.id = guests.invitation_id and i.owner_id = (select auth.uid())
  ));

-- RSVPs: couples read, only the server writes ----------------------------------

grant select on public.rsvps to authenticated;

create policy "Couples read RSVPs of their guests"
  on public.rsvps for select to authenticated
  using (exists (
    select 1 from public.guests g
    join public.invitations i on i.id = g.invitation_id
    where g.id = rsvps.guest_id and i.owner_id = (select auth.uid())
  ));

-- orders, webhook_events, rate_limits: no grants and no policies for anon or authenticated.
-- RLS stays enabled so a future accidental grant still exposes no rows.
