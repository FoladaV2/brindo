"""Generate the Brindo wordmark and monogram as SVG path data from the display font.

Usage: python scripts/build-wordmark.py > src/components/ui/wordmark-paths.ts
Requires fontTools (pip install fonttools). Re-run only if the font or spacing changes.
"""
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.recordingPen import DecomposingRecordingPen

FONT = "assets/fonts/TBCContracticaCAPS-Medium.ttf"
WORD = "brindo"
TRACK = 6  # extra font units between letters; a touch of air at small sizes

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
ascent = 800  # crop: tallest letter (b, d) reaches 777


def pair_kern(left, right):
    """Read a pair adjustment from GPOS PairPos lookups (format 1 and 2)."""
    gpos = font["GPOS"].table
    for lookup in gpos.LookupList.Lookup:
        for sub in lookup.SubTable:
            if lookup.LookupType == 9:
                sub = sub.ExtSubTable
            if getattr(sub, "LookupType", lookup.LookupType) != 2:
                continue
            if left not in sub.Coverage.glyphs:
                continue
            if sub.Format == 1:
                idx = sub.Coverage.glyphs.index(left)
                for pvr in sub.PairSet[idx].PairValueRecord:
                    if pvr.SecondGlyph == right and pvr.Value1:
                        return getattr(pvr.Value1, "XAdvance", 0) or 0
            elif sub.Format == 2:
                c1 = sub.ClassDef1.classDefs.get(left, 0)
                c2 = sub.ClassDef2.classDefs.get(right, 0)
                rec = sub.Class1Record[c1].Class2Record[c2]
                if rec.Value1:
                    return getattr(rec.Value1, "XAdvance", 0) or 0
    return 0


def contours_of(name):
    rec = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(rec)
    out, cur = [], []
    for op, args in rec.value:
        cur.append((op, args))
        if op in ("closePath", "endPath"):
            out.append(cur)
            cur = []
    return out


def draw(contours, dx):
    pen = SVGPathPen(None)
    # flip y: font units are y-up, SVG is y-down
    tpen = TransformPen(pen, (1, 0, 0, -1, dx, ascent))
    for c in contours:
        for op, args in c:
            getattr(tpen, op)(*args)
    return pen.getCommands()


def build(word):
    x, parts, bubble = 0, [], None
    names = [cmap[ord(ch)] for ch in word]
    for i, name in enumerate(names):
        cs = contours_of(name)
        if word[i] == "i":
            # drop the tittle (the contour sitting above x-height) and remember where it was
            tittle = [c for c in cs if min(p[1] for op, a in c for p in a) > 550][0]
            pts = [p for op, a in tittle for p in a]
            cx = (min(p[0] for p in pts) + max(p[0] for p in pts)) / 2 + x
            cy = (min(p[1] for p in pts) + max(p[1] for p in pts)) / 2
            r = (max(p[0] for p in pts) - min(p[0] for p in pts)) / 2
            cs = [c for c in cs if c is not tittle]
            # the bubble: a little smaller than the dot and lifted, so it reads as rising
            bubble = (round(cx, 1), round(ascent - cy - 30, 1), round(r * 0.96, 1))
        parts.append(draw(cs, x))
        x += font["hmtx"][name][0] + TRACK
        if i + 1 < len(names):
            x += pair_kern(name, names[i + 1])
    width = x - TRACK
    return " ".join(parts), round(width), bubble


word_path, word_w, word_bubble = build(WORD)

# Monogram: the "b" with a bubble rising off its shoulder, using the same bubble size.
b = cmap[ord("b")]
mono_path = draw(contours_of(b), 0)
mono_w = font["hmtx"][b][0]
r = word_bubble[2]
mono_bubble = (mono_w - 20, 170, r)

print("// Generated by scripts/build-wordmark.py from the display font. Do not edit by hand.")
print(f"export const WORDMARK = {{ width: {word_w}, height: {ascent + 10}, path: {word_path!r}, bubble: {{ cx: {word_bubble[0]}, cy: {word_bubble[1]}, r: {word_bubble[2]} }} }} as const;")
print(f"export const MONOGRAM = {{ width: {mono_w + 40}, height: {ascent + 10}, path: {mono_path!r}, bubble: {{ cx: {mono_bubble[0]}, cy: {mono_bubble[1]}, r: {mono_bubble[2]} }} }} as const;")
