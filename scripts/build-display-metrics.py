"""Generate advance widths of the display font, so the server can fit invitation names without JS.

Usage: python scripts/build-display-metrics.py > src/lib/invitations/display-metrics.ts
Requires fontTools (pip install fonttools). Re-run only if the display font changes.
"""
import json

from fontTools.ttLib import TTFont

FONT = "assets/fonts/TBCContracticaCAPS-Regular.ttf"
# Everything a name may contain (see NAME_PATTERN in schema.ts): Latin, Latin-1 letters, modern Georgian.
CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xC0, 0x100)) + list(range(0x10D0, 0x10F1)) + [0x2019]

font = TTFont(FONT)
upm = font["head"].unitsPerEm
cmap = font.getBestCmap()
hmtx = font["hmtx"]

widths = {}
for cp in CODEPOINTS:
    if cp in cmap:
        widths[cp] = hmtx[cmap[cp]][0]

georgian = [w for cp, w in widths.items() if 0x10D0 <= cp <= 0x10F0]
fallback = max(georgian)

print("// Generated by scripts/build-display-metrics.py from TBC Contractica CAPS Regular. Do not edit.")
print(f"export const UNITS_PER_EM = {upm};")
print("/** Width used for any character not in the table: the widest Georgian letter, so fitting errs small. */")
print(f"export const FALLBACK_ADVANCE = {fallback};")
print("export const ADVANCE: Record<string, number> = {")
for cp, w in widths.items():
    print(f"  {json.dumps(chr(cp))}: {w},")
print("};")
